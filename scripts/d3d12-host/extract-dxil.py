#!/usr/bin/env python3
"""Extract the rung-3 shaders from vkd3d-proton's test sources.

Writes a C header with the shaders of the first test in
tests/d3d12_geometry_shader.c: a pass-through vertex shader (SV_POSITION +
COLOR) and a pixel shader returning COLOR, each as a signed DXIL container
and as DXBC (SM 4/5) from the same HLSL. The bytes
are vkd3d-proton test data (LGPL-2.1); the header is generated into build/
and never committed.

usage: extract-dxil.py <vkd3d-proton tree> <out.h>
"""
import re
import sys

src = open(f"{sys.argv[1]}/tests/d3d12_geometry_shader.c").read()

def grab(name):
    m = re.search(r"static const (BYTE|DWORD) %s\[\] =\s*\{(.*?)\};" % name, src, re.S)
    if not m:
        sys.exit(f"{name} not found")
    if m.group(1) == "BYTE":
        data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})\b", m.group(2)))
    else:
        data = b"".join(int(x, 16).to_bytes(4, "little") for x in re.findall(r"0x([0-9a-fA-F]{8})\b", m.group(2)))
    if data[:4] != b"DXBC" or data[4:20] == bytes(16):
        sys.exit(f"{name} is not a signed shader container")
    return data

with open(sys.argv[2], "w") as out:
    out.write("/* Generated by scripts/d3d12-host/extract-dxil.py from vkd3d-proton\n"
              " * tests/d3d12_geometry_shader.c (LGPL-2.1 test data). Do not commit. */\n")
    for c_name, src_name in (("rung3_vs_dxil", "vs_code_dxil"), ("rung3_ps_dxil", "ps_code_dxil"),
                             ("rung3_vs_dxbc", "vs_code_dxbc"), ("rung3_ps_dxbc", "ps_code_dxbc")):
        data = grab(src_name)
        out.write(f"static const unsigned char {c_name}[{len(data)}] = {{\n")
        for i in range(0, len(data), 16):
            out.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
        out.write("};\n")
print(f"wrote {sys.argv[2]}")
